//! Zwischenablage auf dem Mac (Teil von clipboard.rs): NSPasteboard lesen und wieder befuellen.
//! Respektiert die Kennzeichen von nspasteboard.org, mit denen Passwortmanager (1Password, Bitwarden,
//! Schluesselbund …) ihre Inhalte vom Verlauf ausschliessen — wie unter Windows.

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardTypeFileURL, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF};
use objc2_foundation::{NSArray, NSString, NSURL};

const EXCLUDE: [&str; 3] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

/// Aendert sich bei jedem neuen Inhalt
pub fn seq() -> u64 {
    NSPasteboard::generalPasteboard().changeCount() as u64
}

/// Dateien, Text oder "Bild vorhanden" — None, wenn leer oder vom Verlauf ausgeschlossen
pub fn peek() -> Option<(Option<Vec<String>>, Option<String>, bool)> {
    let pb = NSPasteboard::generalPasteboard();
    let types: Vec<String> = pb.types()?.iter().map(|t| t.to_string()).collect();
    if types.iter().any(|t| EXCLUDE.contains(&t.as_str())) {
        return None;
    }
    let (file_t, str_t, png_t, tiff_t) =
        unsafe { (NSPasteboardTypeFileURL, NSPasteboardTypeString, NSPasteboardTypePNG, NSPasteboardTypeTIFF) };
    let files: Vec<String> = pb
        .pasteboardItems()
        .map(|items| {
            items
                .iter()
                .filter_map(|it| it.stringForType(file_t))
                .filter_map(|u| NSURL::URLWithString(&u))
                .filter_map(|u| u.path())
                .map(|p| p.to_string())
                .collect()
        })
        .unwrap_or_default();
    let files = (!files.is_empty()).then_some(files);
    let text = if files.is_none() { pb.stringForType(str_t).map(|s| s.to_string()).filter(|t| !t.trim().is_empty()) } else { None };
    let has = |t: &NSString| types.iter().any(|x| *x == t.to_string());
    let image = files.is_none() && text.is_none() && (has(png_t) || has(tiff_t));
    Some((files, text, image))
}

pub fn set_text(t: &str) -> Result<(), String> {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    if pb.setString_forType(&NSString::from_str(t), unsafe { NSPasteboardTypeString }) {
        Ok(())
    } else {
        Err("Text konnte nicht kopiert werden".into())
    }
}

pub fn set_files(files: &[String]) -> Result<(), String> {
    let urls: Vec<Retained<ProtocolObject<dyn objc2_app_kit::NSPasteboardWriting>>> = files
        .iter()
        .map(|f| ProtocolObject::from_retained(NSURL::fileURLWithPath(&NSString::from_str(f))))
        .collect();
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    if pb.writeObjects(&NSArray::from_retained_slice(&urls)) {
        Ok(())
    } else {
        Err("Dateien konnten nicht kopiert werden".into())
    }
}
